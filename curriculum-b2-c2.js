function createAdvancedLesson(language, config, level, topic, topicIndex, lessonIndex, vocabulary) {
  const scene = topic[2][lessonIndex];
  const grammar = advancedGrammar[level][topicIndex];
  const vocabularyWord = vocabulary[(lessonIndex * 3) % vocabulary.length];
  const quizWord = vocabulary[(lessonIndex * 3 + 1) % vocabulary.length];
  const distractors = vocabulary.filter((word) => word.translation !== quizWord.translation).slice(0, 2);
  const targetExample = config.examples[topicIndex];

  return {
    id: `${level.toLowerCase()}-${topicIndex + 1}-${lessonIndex + 1}`,
    title: scene[0],
    minutes: level === "B2" ? 16 : level === "C1" ? 18 : 20,
    objective: scene[1],
    vocabulary,
    steps: [
      {
        type: "vocabulary",
        title: `Léxico de precisión · ${level}`,
        instruction: "Estudia los términos y expresiones. Elige cuáles son útiles para defender una idea, matizarla y responder a otra perspectiva.",
        itemIds: vocabulary.map((word) => word.target)
      },
      {
        type: "grammar",
        title: grammar[0],
        explanation: grammar[1],
        pattern: grammar[2],
        patternLanguage: "es",
        examples: [{ target: targetExample, translation: advancedExampleTranslations[topicIndex] }],
        tip: grammar[3]
      },
      {
        type: "fillBlank",
        title: "Recuperación activa del léxico",
        prompt: `Escribe en ${config.name} la expresión que significa «${vocabularyWord.translation}».`,
        answer: vocabularyWord.target,
        acceptedAnswers: [vocabularyWord.target],
        hint: `Vuelve a las fichas léxicas de «${topic[0]}» y comprueba la ortografía.`
      },
      {
        type: "dialogue",
        title: "Interacción y mediación",
        scene: `Situación: ${scene[1]} Escucha la postura de la otra persona y responde de forma pertinente, precisa y respetuosa.`,
        turns: [{
          speaker: "Interlocutor",
          [language]: config.interaction[0],
          es: config.interaction[1],
          options: [
            { [language]: config.interaction[2], es: config.interaction[3], correct: true },
            { [language]: config.interaction[4], es: config.interaction[5], correct: false }
          ]
        }]
      },
      {
        type: "production",
        title: "Producción avanzada",
        prompt: `${scene[1]} Desarrolla una respuesta con una tesis, evidencia o ejemplo, un matiz y una conclusión proporcionada.`,
        frame: "Tesis → evidencia o ejemplo → matiz / objeción → conclusión.",
        model: targetExample,
        privacyNote: "Puedes usar situaciones ficticias y no necesitas grabarte ni compartir información personal."
      },
      {
        type: "multipleChoice",
        title: "Mini-quiz",
        prompt: `¿Qué término significa «${quizWord.translation}»?`,
        options: [quizWord.target, ...distractors.map((word) => word.target)],
        answer: quizWord.target,
        feedback: `«${quizWord.target}» significa «${quizWord.translation}». ${grammar[3]}`
      }
    ]
  };
}

