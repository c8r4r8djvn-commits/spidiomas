function createMultilingualA2Lesson(config, topic, topicIndex, lessonIndex, vocab, examples) {
  const grammar = config.grammar[topicIndex];
  const example = examples[topicIndex];
  const distractors = [examples[(topicIndex + 1) % examples.length], examples[(topicIndex + 2) % examples.length]];
  const vocabulary = vocab;
  const fillIndex = (lessonIndex * 3) % vocabulary.length;
  const quizIndex = (lessonIndex * 3 + 1) % vocabulary.length;
  const fillWord = vocabulary[fillIndex];
  const quizWord = vocabulary[quizIndex];
  const quizOptions = [
    quizWord.target,
    vocabulary[(quizIndex + 1) % vocabulary.length].target,
    vocabulary[(quizIndex + 2) % vocabulary.length].target
  ];
  const scene = topic.scenes[lessonIndex];

  return {
    id: `${topic.id}-${lessonIndex + 1}`,
    title: scene[0],
    minutes: 10,
    objective: scene[1],
    vocabulary,
    steps: [
      {
        type: "vocabulary",
        title: "Vocabulario clave en contexto",
        instruction: "Lee y escucha las expresiones. Fíjate en su significado y en las diferencias entre el idioma meta y el español.",
        itemIds: vocabulary.map((word) => word.target)
      },
      {
        type: "grammar",
        title: grammar[0],
        explanation: grammar[1],
        pattern: grammar[2],
        examples: [
          { target: example.target, translation: example.translation },
          { target: distractors[0].target, translation: distractors[0].translation }
        ],
        tip: grammar[3]
      },
      {
        type: "fillBlank",
        title: "Recuperación de vocabulario",
        prompt: `¿Cómo se dice «${fillWord.translation}» en ${config.name}?`,
        answer: fillWord.target,
        acceptedAnswers: [fillWord.target],
        hint: `Repasa el vocabulario de «${topic.title}» y vuelve a leer el ejemplo de gramática.`
      },
      {
        type: "dialogue",
        title: "Comprende y responde",
        scene: `Situación: ${scene[1]} Una persona pide ayuda. Elige una respuesta natural.`,
        turns: [{
          speaker: "Interlocutor",
          it: config.interaction[0],
          es: config.interaction[1],
          options: [
            { it: config.interaction[2], es: "Claro. ¿Qué necesita?", correct: true },
            { it: config.interaction[3], es: "El tren sale a las ocho.", correct: false }
          ]
        }]
      },
      {
        type: "production",
        title: "Producción libre",
        prompt: `${scene[1]} Incluye al menos tres palabras del vocabulario clave y una estructura de esta lección.`,
        frame: "Organiza tu respuesta con una idea inicial, dos detalles y una frase final.",
        model: `${example.target} — ${example.translation}`,
        privacyNote: "Usa datos inventados; no incluyas direcciones, documentos ni información médica personal."
      },
      {
        type: "multipleChoice",
        title: "Mini-quiz",
        prompt: `¿Qué palabra significa «${quizWord.translation}» en ${config.name}?`,
        options: quizOptions,
        answer: quizWord.target,
        feedback: `«${quizWord.target}» significa «${quizWord.translation}». ${grammar[3]}`
      }
    ]
  };
}

function createMultilingualA2Course(language, config) {
  const vocabByTopic = config.words[0].map((group, topicIndex) => [
    ...group.split(",").map((target, index) => ({
      target,
      translation: a2Topics[topicIndex].vocabularyEs[index]
    })),
    ...config.commonWords.map(([target, translation]) => ({ target, translation }))
  ]);
  const examples = config.examples.map((target, index) => ({
    target,
    translation: [
      "Normalmente voy al trabajo en autobús, pero hoy camino.",
      "Cuando era pequeño/a, jugaba en el patio después de la escuela.",
      "Envié el paquete, pero todavía no ha llegado.",
      "Primero mezcla los ingredientes y después hornea el pan.",
      "Vamos a visitar la ciudad la semana que viene.",
      "¿Podría ayudarme a rellenar este formulario, por favor?",
      "Me duele la cabeza, así que debería descansar."
    ][index]
  }));
  const roadmap = a2Topics.map((topic, index) => ({
    id: topic.id,
    title: topic.title,
    canDo: topic.canDo,
    grammar: config.grammar[index][0],
    sounds: config.sounds,
    vocabulary: topic.vocabularyEs.join(", "),
    game: topic.scenes[index % topic.scenes.length][0]
  }));

  return {
    metadata: {
      language,
      languageName: config.name,
      supportLanguage: "es",
      speechLanguage: config.speech,
      level: "A2",
      audience: "Hispanohablantes que ya completaron los fundamentos A1",
      estimatedMinutes: 560,
      design: "Siete unidades temáticas con objetivos comunicativos, vocabulario, gramática en contexto, práctica, producción y evaluación formativa",
      contentNote: "Material original de nivel A2 alineado con objetivos comunicativos del MCER; no reproduce libros de texto."
    },
    roadmap,
    units: a2Topics.map((topic, topicIndex) => ({
      id: topic.id,
      title: topic.title,
      lessons: topic.scenes.map((_, lessonIndex) => {
        const unitVocabulary = vocabByTopic[topicIndex];
        const count = Math.min(15, unitVocabulary.length);
        const lastStart = unitVocabulary.length - count;
        const start = topic.scenes.length > 1
          ? Math.round((lessonIndex / (topic.scenes.length - 1)) * lastStart)
          : 0;
        return createMultilingualA2Lesson(
          config,
          topic,
          topicIndex,
          lessonIndex,
          unitVocabulary.slice(start, start + count),
          examples
        );
      })
    }))
  };
}

